"""``.operonx/catalog.md``: every op, graph, job and service the project declares, generated from its code.

An assistant reads it before writing a new op, so it reuses one that exists. Nobody maintains it:
:func:`operonx.guide.sync` (``operonx init``, ``operonx guide``) rewrites it from ``src/`` and ``app/``. It reads
source only (``ast``), so a project that does not import still gets one.
"""

from __future__ import annotations

import ast
from pathlib import Path
from typing import Iterator, List, Optional, Tuple

__all__ = ["PATH", "render", "write"]

#: Where the catalog is, relative to the project's root.
PATH = Path(".operonx") / "catalog.md"
_ROOTS = ("src", "app")
_SKIP = {"__pycache__", ".venv", "venv", "node_modules", "tests"}

_HEAD = """# Catalog

Generated by `operonx guide` from `src/` and `app/`; never edit it. Before writing an op, a graph or a job,
look here for one that exists.
"""


def _named(node: ast.expr) -> str:
    """``op`` for ``@op``, ``@op(...)``, ``@operonx.op``."""
    if isinstance(node, ast.Call):
        node = node.func
    return (
        node.attr
        if isinstance(node, ast.Attribute)
        else node.id
        if isinstance(node, ast.Name)
        else ""
    )


def _signature(fn: ast.AST) -> str:
    args = ast.unparse(fn.args)  # type: ignore[attr-defined]
    returns = f" -> {ast.unparse(fn.returns)}" if fn.returns else ""  # type: ignore[attr-defined]
    return f"{fn.name}({args}){returns}"  # type: ignore[attr-defined]


def _first_line(fn: ast.AST) -> str:
    """The docstring's first sentence, on one line."""
    doc = (ast.get_docstring(fn) or "").strip()  # type: ignore[arg-type]
    para = " ".join(doc.split("\n\n")[0].split())
    end = para.find(". ")
    return para if end == -1 else para[: end + 1]


def _call_name(call: ast.Call) -> Optional[str]:
    if call.args and isinstance(call.args[0], ast.Constant) and isinstance(call.args[0].value, str):
        return call.args[0].value
    for kw in call.keywords:
        if kw.arg == "name" and isinstance(kw.value, ast.Constant):
            return str(kw.value.value)
    return None


def _keyword(call: ast.Call, name: str) -> str:
    return next((ast.unparse(k.value) for k in call.keywords if k.arg == name), "")


def _scan(root: Path) -> Iterator[Tuple[str, str, str, str]]:
    """(kind, what, where, line of doc) per declaration, kind one of op, graph, job, service."""
    for top in _ROOTS:
        base = root / top
        for path in sorted(base.rglob("*.py")) if base.is_dir() else ():
            rel = path.relative_to(root)
            if _SKIP & set(rel.parts) or path.name.startswith("test_"):
                continue
            try:
                tree = ast.parse(path.read_text(encoding="utf-8"))
            except (SyntaxError, UnicodeDecodeError):
                continue
            for n in ast.walk(tree):
                where = f"{rel.as_posix()}:{getattr(n, 'lineno', 0)}"
                if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    kinds = {_named(d) for d in n.decorator_list} & {"op", "graph"}
                    for kind in kinds:
                        yield kind, f"`{_signature(n)}`", where, _first_line(n)
                elif isinstance(n, ast.Call) and _named(n.func) in {"Job", "Service"}:
                    name = _call_name(n)
                    if name is None:
                        continue
                    kind = _named(n.func).lower()
                    graph = _keyword(n, "graph")
                    yield (
                        kind,
                        f"`{name}`" + (f" runs `{graph}`" if graph else ""),
                        where,
                        _keyword(n, "description"),
                    )


def render(root: Path) -> str:
    """The catalog of the project at *root*."""
    found = list(_scan(Path(root)))
    out: List[str] = [_HEAD]
    for kind, title in (
        ("op", "Ops"),
        ("graph", "Graphs"),
        ("job", "Jobs"),
        ("service", "Services"),
    ):
        rows = [f for f in found if f[0] == kind]
        if not rows:
            continue
        out.append(f"## {title}\n")
        for _, what, where, doc in rows:
            doc = doc.strip("\"'")
            out.append(f"- {what} · {where}" + (f" · {doc}" if doc else ""))
        out.append("")
    return "\n".join(out).rstrip("\n") + "\n"


def write(root: Path) -> bool:
    """Write the catalog of the project at *root*; ``True`` when it changed."""
    target = Path(root) / PATH
    text = render(root)
    if target.is_file() and target.read_text(encoding="utf-8") == text:
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8")
    return True
